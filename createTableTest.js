/**
 * CSVをパースした2次元配列から階層構造を構築する。
 *
 * @param {string[][]} db ヘッダー行を含む2次元配列
 * @returns {Map} major -> middle -> minor -> courses
 */
function createHierarchy(db) {
    if (db.length === 0) {
        throw new Error("DBが空です");
    }

    // カラム名から添え字を取得
    const header = new Map(
        db[0].map((name, index) => [name, index])
    );

    const requiredColumns = [
        "id", "name", "year", "credits",
        "major", "middle", "minor",
    ];

    for (const column of requiredColumns) {
        if (!header.has(column)) {
            throw new Error(`必須カラムがありません: ${column}`);
        }
    }

    const get = (row, column) => row[header.get(column)];

    // "1" -> [1], "2-3" -> [2, 3]
    function parseYears(value) {
        const match = /^(\d+)(?:-(\d+))?$/.exec(value);

        if (!match) {
            throw new Error(`不正な開講学年: ${value}`);
        }

        const start = Number(match[1]);
        const end = Number(match[2] ?? match[1]);

        if (start < 1 || end < start) {
            throw new Error(`不正な開講学年: ${value}`);
        }

        return Array.from(
            { length: end - start + 1 },
            (_, i) => start + i
        );
    }

    const hierarchy = new Map();

    for (const row of db.slice(1)) {
        if (row.every(value => value === "")) continue;

        const major = get(row, "major");
        const middle = get(row, "middle");
        const minor = get(row, "minor");

        if (!major || !middle || !minor) {
            throw new Error(
                `分類が未設定の講義があります: ${get(row, "id")}`
            );
        }

        const course = {
            id: get(row, "id"),
            name: get(row, "name"),
            year: get(row, "year"),
            years: parseYears(get(row, "year")),
            credits: Number(get(row, "credits")),
            raw: row,
        };

        // major
        if (!hierarchy.has(major)) {
            hierarchy.set(major, {
                count: 0,
                middles: new Map(),
            });
        }

        const majorNode = hierarchy.get(major);
        majorNode.count++;

        // middle
        if (!majorNode.middles.has(middle)) {
            majorNode.middles.set(middle, {
                count: 0,
                minors: new Map(),
            });
        }

        const middleNode = majorNode.middles.get(middle);
        middleNode.count++;

        // minor
        if (!middleNode.minors.has(minor)) {
            middleNode.minors.set(minor, {
                count: 0,
                courses: [],
                yearCounts: new Map(),
            });
        }

        const minorNode = middleNode.minors.get(minor);
        minorNode.count++;
        minorNode.courses.push(course);

        // 開講学年ごとの占有数を集計
        for (const year of course.years) {
            minorNode.yearCounts.set(
                year,
                (minorNode.yearCounts.get(year) ?? 0) + 1
            );
        }
    }

    // 各minorの必要行数を計算
    for (const majorNode of hierarchy.values()) {
        for (const middleNode of majorNode.middles.values()) {
            for (const minorNode of middleNode.minors.values()) {
                minorNode.requiredRows = Math.max(
                    0,
                    ...minorNode.yearCounts.values()
                );
            }
        }
    }

    return hierarchy;
}

